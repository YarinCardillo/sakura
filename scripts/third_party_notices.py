"""Write THIRD_PARTY_NOTICES from the dependency trees: the Rust crates the app is built from on its
three systems and the fonts it carries.

Each distinct licence text is printed once, followed by the packages it covers. The texts are read from
the packages themselves in cargo's registry, so run it after a build.

usage: third_party_notices.py > THIRD_PARTY_NOTICES
       third_party_notices.py --licenses > <package>/THIRD_PARTY_LICENSES
Environment: SAKURA_CARGO (the cargo command, default cargo), CARGO_HOME.
"""
import hashlib
import json
import os
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LICENCE_FILE_PREFIXES = ("license", "licence", "copying", "unlicense", "notice")
WORKSPACE_PREFIX = "sakura-"
SEPARATOR = "-" * 78
HEADER = """Sakura: third party notices

Sakura is licensed under AGPL-3.0-only (see LICENSE). It is built from the packages below, each under
its own licence. This file is generated by scripts/third_party_notices.py; do not edit it by hand.

Not distributed with Sakura, installed by you and under their own terms: Docker or OrbStack, the
container image the service builds on your machine (Node.js, the agents' command line tools, Chromium,
tinyproxy).
"""


def print_adaptations():
    """Identify adapted source files and preserve the icon notices verbatim."""
    print("Zed terminal adaptations, modified for Sakura in November 2026, GPL-3.0-or-later, Copyright Zed Industries:")
    upstream = "https://github.com/zed-industries/zed/blob/d2a4fb6/"
    sources = {
        "ime.rs": "crates/terminal_view/src/terminal_element.rs",
        "grid_view.rs": "crates/terminal_view/src/terminal_element.rs",
        "overlay.rs": "crates/terminal_view/src/terminal_element.rs",
        "rows.rs": "crates/terminal_view/src/terminal_element.rs",
        "keys.rs": "crates/terminal/src/mappings/keys.rs",
        "mouse.rs": "crates/terminal/src/mappings/mouse.rs",
        "pointer.rs": "crates/terminal/src/terminal.rs",
    }
    for name, source in sources.items():
        print(f"crates/sakura-terminal/src/{name}: {upstream}{source}")
    print("GPL text: LICENSES/GPL-3.0-or-later.txt. Combined with Sakura under section 13.")
    print("Modified Lucide panel-left and panel-right icons:")
    print("crates/sakura-app/assets/icons/panel-left-filled.svg")
    print("crates/sakura-app/assets/icons/panel-right-filled.svg")
    print("https://github.com/lucide-icons/lucide (ISC, including Feather MIT)")
    print((ROOT / "LICENSES/Lucide-ISC-Feather-MIT.txt").read_text())


def cargo_packages():
    """(name, version, licence expression, repository) of every crate in the app's build graph."""
    command = [os.environ.get("SAKURA_CARGO", "cargo"), "tree", "--locked", "--workspace", "--target", "all",
               "--edges", "normal,build", "--prefix", "none", "--format", "{p}|{l}|{r}"]
    output = subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True).stdout
    packages = set()
    for line in output.splitlines():
        if not line.strip():
            continue
        package, _, rest = line.removesuffix(" (*)").partition("|")
        licence, _, repository = rest.partition("|")
        name, version = package.split()[:2]
        if not name.startswith(WORKSPACE_PREFIX):
            packages.add((name, version.lstrip("v"), licence.strip(), repository.strip()))
    return sorted(packages)


def registry_folders():
    """The folders cargo unpacked crates into."""
    home = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))
    return sorted((home / "registry" / "src").glob("*"))


def licence_texts(folder):
    """The licence and notice files at the top of a package's folder, as (file name, text)."""
    if not folder.is_dir():
        return []
    files = [item for item in sorted(folder.iterdir())
             if item.is_file() and item.name.lower().startswith(LICENCE_FILE_PREFIXES)]
    return [(item.name, item.read_text(errors="replace").strip()) for item in files]


def crate_folder(name, version):
    """Where cargo unpacked `name` at `version`, or a path that does not exist."""
    for registry in registry_folders():
        if (registry / f"{name}-{version}").is_dir():
            return registry / f"{name}-{version}"
    return Path("/nonexistent")


def collect():
    """Group every package under each distinct licence text; list apart those that publish none."""
    by_text, titles, without_text = defaultdict(list), {}, []
    sources = [(f"{name} {version}", licence, address, crate_folder(name, version), "crate")
               for name, version, licence, address in cargo_packages()]
    for label, licence, address, folder, kind in sources:
        line = f"{label} ({kind}; {licence or 'licence not declared'}) {address}".rstrip()
        texts = licence_texts(folder)
        if not texts:
            without_text.append(line)
        for file_name, text in texts:
            key = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            by_text[key].append(line)
            titles.setdefault(key, (file_name, text))
    return by_text, titles, without_text


def print_inventory():
    """Print dependency identities and licence identifiers for the source repository."""
    print("Sakura: third party notices\n")
    print("Sakura is AGPL-3.0-only (see LICENSE). Dependencies have their own licences.")
    print("Packaged builds carry their original copyright and licence texts in THIRD_PARTY_LICENSES.\n")
    print("Geist Mono (font; SIL Open Font License 1.1) https://github.com/vercel/geist-font\n")
    print_adaptations()
    print("Rust packages (the build graph for all supported platforms):")
    for name, version, licence, _ in cargo_packages():
        print(f"{name} {version} ({licence or 'licence not declared'}) https://crates.io/crates/{name}/{version}")
    print("\nInstalled separately: Docker or OrbStack; the container image and its tools.")


def print_licenses():
    """Print original upstream copyright and licence texts for distributed binaries."""
    by_text, titles, without_text = collect()
    print(HEADER)
    print_adaptations()
    print((ROOT / "LICENSES/GPL-3.0-or-later.txt").read_text())
    print(SEPARATOR)
    print("Geist Mono (font, SIL Open Font License 1.1) https://github.com/vercel/geist-font")
    print((ROOT / "crates/sakura-app/assets/fonts/OFL.txt").read_text())
    if without_text:
        print(SEPARATOR)
        print("Packages whose published form carries no licence file; the licence each declares is named:\n")
        print("\n".join(sorted(without_text)))
    for key in sorted(by_text, key=lambda key: (-len(by_text[key]), titles[key][0], key)):
        print(SEPARATOR)
        print(f"The following text ({titles[key][0]}) covers:\n")
        print("\n".join(sorted(set(by_text[key]))))
        print()
        print(titles[key][1])
    print(SEPARATOR)


if __name__ == "__main__":
    try:
        if sys.argv[1:] == ["--licenses"]:
            print_licenses()
        elif not sys.argv[1:]:
            print_inventory()
        else:
            sys.exit(__doc__)
    except (subprocess.CalledProcessError, OSError) as error:
        sys.exit(f"third_party_notices: {error}")
