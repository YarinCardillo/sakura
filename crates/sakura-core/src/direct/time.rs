//! Seconds since the epoch written as the service wrote times: ISO 8601 in UTC, to the second.

const SECONDS_PER_DAY: i64 = 86_400;

/// `2026-11-11T13:45:00Z` for the seconds `seconds`.
pub fn iso(seconds: i64) -> String {
    let (days, rest) = (
        seconds.div_euclid(SECONDS_PER_DAY),
        seconds.rem_euclid(SECONDS_PER_DAY),
    );
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        rest / 3600,
        rest % 3600 / 60,
        rest % 60
    )
}

/// The Gregorian date of a day counted from the epoch (Howard Hinnant's `civil_from_days`).
fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let shifted = days + 719_468;
    let era = shifted.div_euclid(146_097);
    let day_of_era = shifted.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_from_march = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * month_from_march + 2) / 5 + 1;
    let month = if month_from_march < 10 {
        month_from_march + 3
    } else {
        month_from_march - 9
    };
    let year = year_of_era + era * 400 + i64::from(month <= 2);
    (year, month, day)
}

#[cfg(test)]
mod tests {
    use super::iso;

    #[test]
    fn times_are_written_in_utc_to_the_second() {
        assert_eq!(iso(0), "1970-01-01T00:00:00Z");
        assert_eq!(iso(951_782_400), "2000-02-29T00:00:00Z");
        assert_eq!(iso(1_762_868_700), "2025-11-11T13:45:00Z");
    }
}
